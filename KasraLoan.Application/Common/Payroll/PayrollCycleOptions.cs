namespace KasraLoan.Application.Common.Payroll
{
    /// <summary>
    /// تنظیمات چرخه‌ی حقوق. همه‌ی پنجره‌های زمانی سیستم به همین یک جا گره خورده‌اند
    /// تا اگر روزِ پرداخت حقوق شرکت عوض شد، فقط اینجا تغییر کند.
    ///
    /// روزها بر اساس <b>تقویم شمسی</b> و به وقت ایران تفسیر می‌شوند.
    ///
    /// ترتیب یک چرخه (پیشنهاد الف):
    ///   روز ۲۵ ماه قبل  → پنجره‌ی انتخاب روش پرداخت قسط باز می‌شود
    ///   روز ۲۸ ماه قبل  → پنجره‌ی تغییر وضعیت اشتغال باز می‌شود
    ///   آخرین روز ماه   → انتخاب روش پرداخت بسته می‌شود
    ///   روز ۱ ماه جاری  → پنجره‌ی وضعیت اشتغال بسته می‌شود؛ لیست حقوق قطعی است
    ///   روز ۲ ماه جاری  → حقوق پرداخت و اقساط کسر می‌شود
    /// </summary>
    public class PayrollCycleOptions
    {
        public const string SectionName = "PayrollCycle";

        /// <summary>روزی از ماه که حقوق پرداخت و کسر اقساط اعمال می‌شود.</summary>
        public int PayrollRunDay { get; set; } = 2;

        /// <summary>
        /// روزی از ماه <b>قبل</b> که کارمند می‌تواند روش پرداخت قسط را انتخاب کند.
        /// پنجره تا پایان همان ماه باز است.
        /// </summary>
        public int PaymentMethodSelectionOpenDay { get; set; } = 25;

        /// <summary>
        /// روزی از ماه <b>قبل</b> که ادمین می‌تواند وضعیت اشتغال را به «غیرفعال» تغییر دهد.
        /// </summary>
        public int EmploymentChangeOpenDay { get; set; } = 28;

        /// <summary>
        /// آخرین روز (در ماه <b>بعد</b>) که تغییر وضعیت اشتغال هنوز پذیرفته می‌شود.
        /// پنجره دور ماه می‌پیچد: از EmploymentChangeOpenDay تا این روز از ماه بعد.
        /// </summary>
        public int EmploymentChangeCloseDay { get; set; } = 1;

        /// <summary>
        /// مهلت تسویه‌ی کل مانده‌ی وام بعد از پایان همکاری (روز).
        /// مطالبه‌ی «همین امروز کل بدهی را بده» غیرواقعی است؛ در عمل مانده از
        /// تسویه‌حسابِ پایان کار برداشت می‌شود و آن هم چند هفته طول می‌کشد.
        /// </summary>
        public int SettlementGraceDays { get; set; } = 30;
    }
}
